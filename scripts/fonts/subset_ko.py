"""Cut Noto Sans KR (variable, all weights) down to the Korean the site shows.

Run after `npm run build` whenever new Korean text lands on the site (check-build fails
when a syllable is missing from the font):

    python3 -m venv ~/.cache/hanguledu/venv && ~/.cache/hanguledu/venv/bin/pip install fonttools brotli
    ~/.cache/hanguledu/venv/bin/python scripts/fonts/subset_ko.py && npm run build

Writes:
  src/fonts/noto-sans-kr.woff2          every Korean character in dist/; loads on every page
  src/fonts/noto-sans-kr.txt            the characters it covers (check-build reads it)
  src/fonts/noto-sans-kr-builder.woff2  syllables only the block builder can make; loads on demand
  src/styles/fonts.css, src/styles/fonts-builder.css   the @font-face rules
"""

import re
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
# Pinned to a google/fonts commit so a rerun cuts from the same outlines.
SRC_URL = 'https://raw.githubusercontent.com/google/fonts/4efc2774c63917927efe769ca845def6bd6debae/ofl/notosanskr/NotoSansKR%5Bwght%5D.ttf'
SRC = Path.home() / '.cache/hanguledu/NotoSansKR-VF.ttf'
KOREAN = re.compile('[ᄀ-ᇿ㄰-㆏가-힣]')
# Latin and punctuation stay with the system font: inside Korean lines they are rare, and
# Latin glyphs with their kerning would add ~45 KB.
EXTRA = [' ', chr(0xA0)]


def site_chars() -> set[str]:
    dist = ROOT / 'dist'
    if not (dist / 'index.html').exists():
        raise SystemExit('dist/ is empty: run `npm run build` first')
    found: set[str] = set()
    for p in dist.rglob('*'):
        if p.suffix in ('.html', '.js', '.json'):
            found.update(KOREAN.findall(p.read_text('utf8')))
    return found


def builder_chars() -> set[str]:
    """Every syllable BlockBuilder.astro can compose from its consonant, vowel and final pickers."""
    src = (ROOT / 'src/components/BlockBuilder.astro').read_text('utf8')
    cons = re.search(r"const CONS = '([^']+)'", src).group(1)
    vows = re.search(r"const VOWS = '([^']+)'", src).group(1)
    fins = re.findall(r"'([^']*)'", re.search(r'const FINS = \[([^\]]+)\]', src).group(1))
    cho = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
    jung = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'
    jong = ['', 'ㄱ', 'ㄲ', 'ㄳ', 'ㄴ', 'ㄵ', 'ㄶ', 'ㄷ', 'ㄹ', 'ㄺ', 'ㄻ', 'ㄼ', 'ㄽ', 'ㄾ', 'ㄿ', 'ㅀ', 'ㅁ', 'ㅂ', 'ㅄ', 'ㅅ', 'ㅆ', 'ㅇ']
    return {
        chr(0xAC00 + (cho.index(c) * 21 + jung.index(v)) * 28 + jong.index(b))
        for c in cons for v in vows for b in fins
    }


def cut(chars: set[str], out: Path) -> list[int]:
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.hinting = False
    opts.name_IDs = ['*']
    font = TTFont(SRC)
    sub = subset.Subsetter(opts)
    sub.populate(text=''.join(chars))
    sub.subset(font)
    font.flavor = 'woff2'
    font.save(out)
    return sorted(font.getBestCmap())


def ranges(cps: list[int]) -> str:
    out, start = [], cps[0]
    for prev, cp in zip(cps, cps[1:] + [None]):
        if cp != prev + 1:
            out.append(f'U+{start:X}' if start == prev else f'U+{start:X}-{prev:X}')
            start = cp
    return ', '.join(out)


def face(file: str, cps: list[int], note: str) -> str:
    return (
        f'/* Generated by scripts/fonts/subset_ko.py. {note} */\n'
        '@font-face {\n'
        '  font-family: "Noto Sans KR";\n'
        '  font-style: normal;\n'
        '  font-weight: 100 900;\n'
        '  font-display: swap;\n'
        f'  src: url("../fonts/{file}") format("woff2");\n'
        f'  unicode-range: {ranges(cps)};\n'
        '}\n'
    )


def main():
    if not SRC.exists():
        SRC.parent.mkdir(parents=True, exist_ok=True)
        print('downloading', SRC_URL)
        urllib.request.urlretrieve(SRC_URL, SRC)

    fonts = ROOT / 'src/fonts'
    fonts.mkdir(exist_ok=True)
    core = site_chars() | set(EXTRA)
    core_cps = cut(core, fonts / 'noto-sans-kr.woff2')
    (fonts / 'noto-sans-kr.txt').write_text(''.join(chr(c) for c in core_cps if KOREAN.match(chr(c))) + '\n', 'utf8')

    extra = builder_chars() - {chr(c) for c in core_cps}
    extra_cps = cut(extra, fonts / 'noto-sans-kr-builder.woff2')

    styles = ROOT / 'src/styles'
    (styles / 'fonts.css').write_text(face('noto-sans-kr.woff2', core_cps, 'Korean on the site, all weights.'), 'utf8')
    (styles / 'fonts-builder.css').write_text(
        face('noto-sans-kr-builder.woff2', extra_cps, 'Syllables only the block builder makes; fetched when one is shown.'), 'utf8')

    for f in ('noto-sans-kr.woff2', 'noto-sans-kr-builder.woff2'):
        print(f'{f}: {(fonts / f).stat().st_size // 1024} KB')
    print(f'core {len(core_cps)} code points, builder {len(extra_cps)}')


if __name__ == '__main__':
    main()
